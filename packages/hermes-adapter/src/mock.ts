import { createHash } from 'node:crypto';
import {
  AdapterError,
  TERMINAL_RUN_STATUSES,
  type AdapterRunEvent,
  type HermesAdapter,
  type ProbeResult,
  type RunRequest,
  type RunState,
} from './types.ts';

export type MockScenario = 'pass' | 'revise_once' | 'never_pass' | 'fail' | 'hang';

export interface MockConfig {
  /** Delay between simulated steps. 0 = run as fast as the event loop allows. */
  stepMs?: number;
  scenario?: MockScenario;
}

interface MockRun {
  id: string;
  req: RunRequest;
  state: RunState;
  events: AdapterRunEvent[];
  listeners: Set<() => void>;
  timer: ReturnType<typeof setTimeout> | null;
  stopRequested: boolean;
}

export const MOCK_DISCLOSURE =
  '> DEMO OUTPUT: generated by the deterministic mock adapter. No AI model or Hermes runtime was used.';

/**
 * Deterministic stand-in for Hermes. Same input -> same output, so UI and orchestration
 * can be tested end to end without a model. Always reports `live: false`; the client
 * labels everything it produces as DEMO.
 */
export class MockHermesAdapter implements HermesAdapter {
  readonly kind = 'mock' as const;
  readonly live = false;
  private readonly runs = new Map<string, MockRun>();
  private readonly byKey = new Map<string, string>();
  private counter = 0;
  readonly stepMs: number;
  scenario: MockScenario;

  constructor(cfg: MockConfig = {}) {
    this.stepMs = cfg.stepMs ?? 400;
    this.scenario = cfg.scenario ?? 'revise_once';
  }

  async probe(): Promise<ProbeResult> {
    return {
      health: {
        adapter: 'mock',
        live: false,
        state: 'ready',
        detail: `Deterministic mock adapter (scenario: ${this.scenario}). Not a live Hermes runtime.`,
        hermesVersion: null,
        checkedAt: new Date().toISOString(),
      },
      enabledToolsets: [],
    };
  }

  async startRun(req: RunRequest): Promise<{ runId: string }> {
    const existing = this.byKey.get(req.idempotencyKey);
    if (existing) return { runId: existing };
    this.counter += 1;
    const id = `mockrun_${this.counter}_${createHash('sha256').update(req.idempotencyKey).digest('hex').slice(0, 8)}`;
    const run: MockRun = {
      id,
      req,
      state: { runId: id, status: 'running', output: null, error: null, usage: null },
      events: [],
      listeners: new Set(),
      timer: null,
      stopRequested: false,
    };
    this.runs.set(id, run);
    this.byKey.set(req.idempotencyKey, id);
    this.schedule(run, 0);
    return { runId: id };
  }

  private emit(run: MockRun, ev: AdapterRunEvent) {
    run.events.push({ ...ev, seq: run.events.length });
    for (const l of run.listeners) l();
  }

  private finish(run: MockRun, patch: Partial<RunState>) {
    run.state = { ...run.state, ...patch };
    this.emit(run, { type: 'terminal', state: run.state, seq: null });
  }

  private schedule(run: MockRun, step: number) {
    run.timer = setTimeout(() => this.step(run, step), this.stepMs);
  }

  private step(run: MockRun, step: number) {
    run.timer = null;
    if (TERMINAL_RUN_STATUSES.includes(run.state.status)) return;
    if (run.stopRequested) {
      // Partial output so the control plane can record what existed at cancellation.
      this.finish(run, { status: 'cancelled', output: partialDraft(run.req), error: 'Stopped on request' });
      return;
    }
    const isRevision = run.req.input.includes('REVISION REQUEST');
    switch (step) {
      case 0:
        this.emit(run, { type: 'progress', summary: 'Reading the project brief', seq: null });
        break;
      case 1:
        this.emit(run, { type: 'tool', name: 'read_brief', phase: 'started', error: false, seq: null });
        break;
      case 2:
        this.emit(run, { type: 'tool', name: 'read_brief', phase: 'completed', error: false, seq: null });
        this.emit(run, { type: 'progress', summary: 'Drafting milestones', seq: null });
        break;
      case 3:
        if (this.scenario === 'hang') {
          this.emit(run, { type: 'progress', summary: 'Still drafting (mock hang scenario)', seq: null });
          this.schedule(run, 3);
          return;
        }
        this.emit(run, { type: 'progress', summary: isRevision ? 'Applying review findings' : 'Writing risks and acceptance criteria', seq: null });
        break;
      default: {
        if (this.scenario === 'fail') {
          this.finish(run, { status: 'failed', error: 'Mock scenario "fail": simulated model error' });
          return;
        }
        const omitRisks = this.scenario === 'never_pass' || (this.scenario === 'revise_once' && !isRevision);
        const output = renderPlan(run.req, { omitRisks });
        this.emit(run, { type: 'delta', text: output, seq: null });
        this.finish(run, {
          status: 'completed',
          output,
          usage: { inputTokens: null, outputTokens: null, costUsd: null },
        });
        return;
      }
    }
    this.schedule(run, step + 1);
  }

  async getRun(runId: string): Promise<RunState | null> {
    const run = this.runs.get(runId);
    return run ? { ...run.state } : null;
  }

  async stopRun(runId: string): Promise<{ accepted: boolean; detail: string }> {
    const run = this.runs.get(runId);
    if (!run) return { accepted: false, detail: 'Unknown run' };
    if (TERMINAL_RUN_STATUSES.includes(run.state.status)) return { accepted: false, detail: `Run already ${run.state.status}` };
    run.stopRequested = true;
    run.state = { ...run.state, status: 'stopping' };
    if (run.timer) {
      clearTimeout(run.timer);
      this.schedule(run, 99);
    }
    return { accepted: true, detail: 'Mock run stopping' };
  }

  async resolveApproval(): Promise<{ resolved: boolean; detail: string }> {
    return { resolved: false, detail: 'The mock adapter never requests tool approvals' };
  }

  async *events(runId: string, opts: { signal: AbortSignal; afterSeq?: number }): AsyncIterable<AdapterRunEvent> {
    const run = this.runs.get(runId);
    if (!run) throw new AdapterError(`Run ${runId} not found`, 'not_found', 404);
    let next = (opts.afterSeq ?? -1) + 1;
    while (!opts.signal.aborted) {
      while (next < run.events.length) {
        const ev = run.events[next++]!;
        yield ev;
        if (ev.type === 'terminal') return;
      }
      await new Promise<void>((resolve) => {
        const wake = () => {
          run.listeners.delete(wake);
          opts.signal.removeEventListener('abort', wake);
          resolve();
        };
        run.listeners.add(wake);
        opts.signal.addEventListener('abort', wake, { once: true });
      });
    }
  }

  /** Test helper: forget every run, as if the runtime restarted. */
  forgetAll() {
    for (const r of this.runs.values()) if (r.timer) clearTimeout(r.timer);
    this.runs.clear();
    this.byKey.clear();
  }
}

function firstLines(text: string, n: number): string[] {
  return text
    .split(/\r?\n/)
    .map((l) => l.replace(/^[#>*\-\s\d.]+/, '').trim())
    .filter((l) => l.length > 3 && !l.startsWith('REVISION REQUEST'))
    .slice(0, n)
    .map((l) => (l.length > 140 ? `${l.slice(0, 139)}…` : l));
}

function titleFrom(input: string): string {
  const m = /^Project title: (.+)$/m.exec(input);
  return m?.[1]?.trim().slice(0, 100) || 'Untitled project';
}

function partialDraft(req: RunRequest): string {
  return `# Implementation Plan: ${titleFrom(req.input)} (PARTIAL)\n\n${MOCK_DISCLOSURE}\n\n## Milestones\n\n1. (drafting interrupted)\n`;
}

/** Deterministic Markdown plan built only from the brief text. */
export function renderPlan(req: RunRequest, opts: { omitRisks: boolean }): string {
  const title = titleFrom(req.input);
  const briefText = (req.input.split('--- BRIEF ---')[1] ?? req.input).split('--- END BRIEF ---')[0] ?? '';
  const points = firstLines(briefText, 6);
  const goals = points.length > 0 ? points : ['Clarify the project goal with the owner'];
  const milestones = [
    `Confirm scope: ${goals[0]}`,
    ...goals.slice(1, 4).map((g) => `Deliver: ${g}`),
    'Review the result against the acceptance criteria and record lessons',
  ];
  const parts = [
    `# Implementation Plan: ${title}`,
    '',
    MOCK_DISCLOSURE,
    '',
    '## Summary',
    '',
    `This plan breaks "${title}" into bounded milestones derived from the provided brief.`,
    '',
    '## Milestones',
    '',
    ...milestones.map((m, i) => `${i + 1}. ${m}`),
    '',
  ];
  if (!opts.omitRisks) {
    parts.push(
      '## Risks',
      '',
      '- Requirements in the brief may be incomplete; unresolved questions go to the owner.',
      '- Estimates are rough until the first milestone is reviewed.',
      '- External services or model providers may process project data.',
      '',
    );
  }
  parts.push(
    '## Acceptance Criteria',
    '',
    '- Every milestone has a reviewable deliverable.',
    '- Open risks have an owner-visible mitigation or are escalated.',
    '- The final review passes against this list.',
    '',
  );
  return parts.join('\n');
}
